import sys, os, json, re
from PIL import Image
import numpy as np
SRC = sys.argv[1]; DST = sys.argv[2]
KEYS = ['simcheong', 'seondal', 'hocheol', 'dongmin', 'haenim', 'dalnim']
POSE_H = 360          # stored height of the p1 standing pose
WALK_FRAMES = 9       # frames 0..8 (frame 9 repeats the contact pose)

def trim(im):
    a = np.array(im); ys, xs = np.where(a[..., 3] > 8)
    return im.crop((xs.min(), ys.min(), xs.max() + 1, ys.max() + 1))

def mid(im):
    a = np.array(im)[..., 3].astype(float); h = a.shape[0]
    band = a[int(h * 0.22):int(h * 0.58)] > 128
    ys, xs = np.where(band)
    return round(float(xs.mean() / a.shape[1]), 3) if len(xs) else 0.5

def clean_floor_glow(im):  # 이동민 walk sheet: purple floor reflection around the boots
    a = np.array(im).astype(int); h = a.shape[0]; r, g, b = a[..., 0], a[..., 1], a[..., 2]
    purple = (b > r + 15) & (b > g + 25) & (np.arange(h)[:, None] > h * 0.8) & (a[..., :3].max(2) > 60)
    a[..., 3] = np.where(purple, 0, a[..., 3])
    return trim(Image.fromarray(a.astype(np.uint8), 'RGBA'))

meta = {}; info = {}
for k in KEYS:
    p1 = Image.open(f'{SRC}/poses/{k}_p1.png'); f = POSE_H / p1.height
    for i in range(1, 6):
        im = Image.open(f'{SRC}/poses/{k}_p{i}.png')
        im = im.resize((round(im.width * f), round(im.height * f)), Image.LANCZOS)
        im.save(f'{DST}/{k}_p{i}.png', optimize=True)
        meta[f'{k}_p{i}'] = {'w': im.width, 'h': im.height, 'mid': mid(im)}
    ground = max(int(open(f'{SRC}/walk/{k}_w{i}.txt').read()) for i in range(WALK_FRAMES))
    w0 = Image.open(f'{SRC}/walk/{k}_w0.png'); fw = min(1.0, 280 / w0.height)
    for i in range(WALK_FRAMES):
        im = Image.open(f'{SRC}/walk/{k}_w{i}.png')
        if k == 'dongmin': im = clean_floor_glow(im)
        lift = ground - int(open(f'{SRC}/walk/{k}_w{i}.txt').read())  # airborne frames keep their height off the floor
        pad = Image.new('RGBA', (im.width, im.height + lift)); pad.paste(im, (0, 0)); im = pad
        im = im.resize((round(im.width * fw), round(im.height * fw)), Image.LANCZOS)
        im.save(f'{DST}/{k}_walk_{i}.png', optimize=True)
        meta[f'{k}_walk_{i}'] = {'w': im.width, 'h': im.height, 'mid': mid(im)}
    info[k] = {'walkH0': round(w0.height * fw)}
    b = Image.open(f'{SRC}/poses/{k}_bust.png'); fb = min(1.0, 1000 / b.height)
    b.resize((round(b.width * fb), round(b.height * fb)), Image.LANCZOS).save(f'{DST}/{k}.png', optimize=True)

# merge into sprite_meta.js (keep the old entries)
txt = open(f'{DST}/sprite_meta.js', encoding='utf8').read()
old = json.loads(txt[txt.index('{'):txt.rindex('}') + 1])
old.update(meta)
open(f'{DST}/sprite_meta.js', 'w', encoding='utf8').write(
    '// generated by tools/cutout_sprites.py — sprite size + foot anchor (0..1)\n'
    '// *_p1..p5 / *_walk_N: 조선야차_캐릭터_애셋_모음_완성본.docx (tools/export_docx_assets.py)\n'
    'const SPRITE_META = ' + json.dumps(old, indent=1, sort_keys=True, ensure_ascii=False) + ';\n')
print(json.dumps(info))
